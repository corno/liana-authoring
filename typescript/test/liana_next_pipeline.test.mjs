test('Liana Next infers constraint metadata without declaring or parsing metadata fields', async () => {
    const model = fixture('resolver')[1]
    const dict = p.literal.dictionary
    const none = p.literal.not_set
    const state = options => ['state', {
        options: dict(Object.fromEntries(Object.entries(options).map(([id, value]) =>
            [id, { constraints: none(), description: none(), value }]))), results: none(),
    }]
    const stateResolver = options => ['state', { options: dict(options) }]
    const signature = entry(model.resolver.signatures.signatures, 'Root')
    const source = ['liana', {
        ...model,
        types: dict({
            Source: { 'root value': state({
                ready: ['group', dict({ label: { description: none(), value: ['simple', 'Text'] } })],
                other: ['nothing', null],
            }) },
            Root: { 'root value': state({ read: ['simple', 'Text'], skip: ['simple', 'Text'] }) },
        }),
        resolver: {
            signatures: { signatures: dict({
                Source: signature,
                Root: { ...signature, parameters: ['local', {
                    lookups: dict({}),
                    types: dict({ source: {
                        type: { location: ['internal', 'Source'] },
                        presence: ['required', null],
                    } }),
                }] },
            }) },
            types: dict({
                Source: { 'root value resolver': stateResolver({
                    ready: { constraints: dict({}), resolver: ['group', dict({ label: { resolver: ['simple', null] } })] },
                    other: { constraints: dict({}), resolver: ['nothing', null] },
                }) },
                Root: { 'root value resolver': stateResolver({
                    read: { constraints: dict({ ready: ['state', {
                        selection: {
                            start: ['parameter', 'source'],
                            tail: { path: p.literal.list([]) },
                        },
                        option: 'ready',
                    }] }), resolver: ['simple', null] },
                    skip: { constraints: dict({}), resolver: ['simple', null] },
                }) },
            }),
        },
    }]
    const rootSignature = entry(source[1].resolver.signatures.signatures, 'Root')
    const importedSource = ['liana', {
        ...source[1],
        imports: dict({ shared: source[1] }),
        types: dict({ Root: entry(source[1].types, 'Root') }),
        resolver: {
            signatures: { signatures: dict({ Root: {
                ...rootSignature,
                parameters: ['local', {
                    lookups: dict({}), types: dict({ source: {
                        type: { location: ['external', { import: 'shared', type: 'Source' }] },
                        presence: ['required', null],
                    } }),
                }],
            } }) },
            types: dict({ Root: entry(source[1].resolver.types, 'Root') }),
        },
    }]
    const bridge = {
        ...model,
        imports: dict({ deep: source[1] }),
        types: dict({ Source: { 'root value': ['component', {
            type: ['external', { import: 'deep', type: 'Source' }], results: none(),
        }] } }),
        root: 'Source',
        resolver: {
            signatures: { signatures: dict({ Source: signature }) },
            types: dict({ Source: { 'root value resolver': ['component', {
                location: ['external', {
                    'schema import': 'deep', 'resolver import': 'deep', signature: 'Source',
                }], arguments: none(), constraints: dict({}),
            }] } }),
        },
    }
    const rootResolver = entry(importedSource[1].resolver.types, 'Root')['root value resolver']
    const readOption = entry(rootResolver[1].options, 'read')
    const ready = entry(readOption.constraints, 'ready')
    const transitiveSource = ['liana', {
        ...importedSource[1], imports: dict({ shared: bridge }),
        resolver: {
            ...importedSource[1].resolver,
            types: dict({ Root: { 'root value resolver': ['state', {
                ...rootResolver[1],
                options: dict({
                    skip: entry(rootResolver[1].options, 'skip'),
                    read: { ...readOption, constraints: dict({ ready: ['state', {
                        ...ready[1], selection: {
                            ...ready[1].selection,
                            tail: { ...ready[1].selection.tail, path: p.literal.list([['component', null]]) },
                        },
                    }] }) },
                }),
            }] } }),
        },
    }]
    for (const schema of [source, importedSource, transitiveSource]) {
        const directory = mkdtempSync(join(tmpdir(), 'liana-next-metadata-'))
        try {
            const generated = pipeline(schema)
            assert.deepEqual(placeholders(generated.pareto), [])
            assert.equal(write(generated.typescript, directory).typescriptPlaceholders, 0)
            assert.deepEqual(typecheck(directory), { status: 'passed' })
            compile(directory)
            const parse = await import(pathToFileURL(join(directory, 'dist/schemas/unresolved/refiners/list_of_characters.js')))
            const resolve = await import(pathToFileURL(join(directory, 'dist/schemas/resolved/refiners/unresolved.js')))
            const serialize = await import(pathToFileURL(join(directory, 'dist/schemas/resolved/transformers/serialized_paragraph.js')))
            const authored = parse.Root(chars('| read "authored"'), abort, { 'tab size': 4 })
            assert.deepEqual(authored, ['read', 'authored'])
            const payload = { label: 'the node' }
            const resolved = resolve.Root(authored, abort, null, { source: ['ready', payload] })
            assert.deepEqual(resolved, ['read', { value: 'authored', meta: { ready: payload } }])
            assert.equal(resolved[1].meta.ready, payload)
            const serialized = serialize.Root(resolved, { indentation: '    ' }).__get_raw().join('\n')
            assert.doesNotMatch(serialized, /meta|the node|~/)
            assert.deepEqual(parse.Root(chars(serialized), abort, { 'tab size': 4 }), authored)
            assert.deepEqual(resolve.Root(['skip', 'ordinary'], abort, null, { source: ['other', null] }), ['skip', 'ordinary'])
            assert.throws(() => resolve.Root(authored, abort, null, { source: ['other', null] }),
                error => error.type === 'unexpected state option' && error.id === 'ready')
        } finally {
            rmSync(directory, { recursive: true })
        }
    }
})

