test('Liana Next identity assertions compare selected nodes, not their contents', async () => {
    const source = `| liana (
        imports: {}
        globals: ( 'simple types': { 'Text': ( type: | text < | \`single line\` ~ | no ~ > ) } )
        types: {
            'Entry': ( 'root value': | group { 'label': < _ | simple 'Text' > } )
            'Entries': ( 'root value': | dictionary < | component < | internal 'Entry' _ > > )
            'Root': ( 'root value': | group {
                'entries': < _ | component < | internal 'Entries' _ > >
                'left': < _ | reference < < < | internal 'Entries' > < [] > > | selected < | acyclic ~ _ > > >
                'right': < _ | reference < < < | internal 'Entries' > < [] > > | selected < | acyclic ~ _ > > >
                'value': < _ | simple 'Text' >
            } )
        }
        resolver: (
            signatures: ( signatures: {
                'Entry': < | local < {} {} > >
                'Entries': < | local < {} {} > >
                'Root': < | local < {} {} > >
            } )
            types: {
                'Entry': < | group { 'label': < | simple ~ > } >
                'Entries': < | dictionary < | component < | internal 'Entry' _ {} > _ > >
                'Root': < | group {
                    'entries': < | component < | internal 'Entries' _ {} > >
                    'left': < | reference < | selected < < | acyclic | \`resolved dictionary\` < < | sibling 'entries' < [ | component ~ ] > > > > {} > > >
                    'right': < | reference < | selected < < | acyclic | \`resolved dictionary\` < < | sibling 'entries' < [ | component ~ ] > > > > {} > > >
                    'value': < | 'assert identity' (
                        left: < | sibling 'left' < [ | reference {} ] > >
                        right: < | sibling 'right' < [ | reference {} ] > >
                        resolver: | simple ~
                    ) >
                } >
            }
        )
        root: 'Root'
    )`
    const directory = mkdtempSync(join(tmpdir(), 'liana-next-identity-'))
    try {
        const schemaPath = join(directory, 'identity.liana_next.lna')
        symlinkSync(fileURLToPath(new URL('.liana/', examples)), join(directory, '.liana'), 'dir')
        writeFileSync(schemaPath, source)
        const generated = pipeline(input(schemaPath))
        assert.deepEqual(placeholders(generated.pareto), [])
        assert.equal(write(generated.typescript, directory).typescriptPlaceholders, 0)
        assert.deepEqual(typecheck(directory), { status: 'passed' })
        compile(directory)
        const resolver = await import(pathToFileURL(join(directory, 'dist/schemas/resolved/refiners/unresolved.js')))
        const instance = {
            entries: p.literal.dictionary({ first: { label: 'equal' }, second: { label: 'equal' } }),
            left: 'first', right: 'first', value: 'passed',
        }
        const output = resolver.Root(instance, abort, null, null)
        assert.equal(output.left['l entry'], output.right['l entry'])
        assert.equal(output.value, 'passed')
        assert.deepEqual(Object.keys(output).sort(), ['entries', 'left', 'right', 'value'])
        assert.throws(() => resolver.Root({ ...instance, right: 'second' }, abort, null, null), error =>
            error.type === 'identity mismatch' && error.path.__get_raw().join('/') === 'Root/value')
        assert.throws(() => resolver.Root({ ...instance, right: 'missing' }, abort, null, null), error =>
            error.type === 'no such entry' && error.id === 'missing')
    } finally {
        rmSync(directory, { recursive: true })
    }
})

